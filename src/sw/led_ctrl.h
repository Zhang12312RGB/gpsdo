#ifndef LED_CTRL_H
#define LED_CTRL_H

#include "xil_types.h"

/*=============================================================================
 * led_ctrl.h -- LED 频率差指示模块（频率差越大，闪烁越快）
 *-----------------------------------------------------------------------------
 * 数据来源 : 卡尔曼滤波器状态量 kalman.X[1]  (频率差, 单位 ppb)
 * 处理     : 取绝对值 |X[1]| -> 映射为闪烁频率 -> 驱动 LED
 * 受控引脚 : E6 = PS_MIO0_5 = PS_MIO0_500 = MIO0_LED = PS LED1
 *            BANK500, 3.3V, "高为灭" -> 低电平点亮
 *
 * 依据文档:
 *   1) 系统架构图(1).pdf   PS(ARM Cortex-A9) 框内 "LED控制模块"
 *        - 引脚标注 "E6 / PS_MIO0_5 / 3.3V 为高 (高为灭)"
 *        - AXI 寄存器表另有 "0x10 LED_CTRL"
 *        - 卡尔曼滤波输出 X[0] X[1], X[1] 引出到显示
 *   2) 闭环控制原理图.pdf  卡尔曼滤波输出 "X1 (频率偏差估计)"
 *   3) 接线图.pdf  备注: "暂时实验LED用来只是频率差的大小, 等串屏出现后改为该功能"
 *   4) ALINX AX7010 用户手册 V1.07  PS BANK500 IO 表
 *        MIO0_LED | PS_MIO0_500 | E6 | PS LED1
 *
 * 为什么默认走 PS GPIO 而不是 AXI 寄存器:
 *   E6 是 PS 侧的 MIO 引脚, PL 无法直接驱动, 只能由 PS 通过 GPIO 控制器
 *   (XGpioPs) 拉高/拉低。因此默认通道是 PS GPIO, 上板即可用, 不需要改 RTL。
 *   若确实要用架构图里的 0x10 LED_CTRL, 见下面"通道选择"。
 *===========================================================================*/

/*---------------------------------------------------------------------------
 * 一、通道选择 (编译期二选一)
 *   LED_USE_PL_REG = 0 : PS GPIO 直接驱动 E6/PS_MIO0_5   [默认, 推荐]
 *   LED_USE_PL_REG = 1 : 写 AXI 寄存器 LED_CTRL(偏移 0x10), 由 PL 输出引脚
 *                        注意需先在 RTL 里实现 0x10 写口, 且 PL 只能驱动
 *                        PL 侧 LED(M14/M15/K16/J16), 驱动不了 PS 的 E6。
 *--------------------------------------------------------------------------*/
#ifndef LED_USE_PL_REG
  #define LED_USE_PL_REG    0
#endif

/*---------------------------------------------------------------------------
 * 二、PS GPIO 配置 (LED_USE_PL_REG = 0 时生效)
 *   MIO 0~31   -> XGpioPs bank/channel 1
 *   MIO 32~53  -> XGpioPs bank/channel 2
 *   MIO 54~85  -> bank/channel 3 (EMIO)
 *--------------------------------------------------------------------------*/
#define LED_MIO_PIN         0U      /* PS_MIO0_500                  */
#define LED_GPIO_DEV_ID     0U      /* 第一个 GPIO 控制器          */

/*---------------------------------------------------------------------------
 * 三、AXI 寄存器 (仅 LED_USE_PL_REG = 1 时生效)
 *   架构图写的是 0x10 LED_CTRL。但当前 gnss_axi_ip_slave.v 的 0x10 是
 *   PPS_COUNT(只读), 所以基地址与偏移需按实际硬件在 led_ctrl.c 顶部覆盖。
 *--------------------------------------------------------------------------*/
#define LED_CTRL_OFFSET     0x10U   /* 架构图: 0x10 LED_CTRL       */
#define LED_BIT_LEVEL       0x01U   /* bit0 = LED 电平             */

/*---------------------------------------------------------------------------
 * 四、闪烁频率映射参数
 *   频率 = 每秒完整亮灭次数(Hz), 亮/灭各占半个周期
 *   |X[1]| 越大 -> 频率越高(闪得越快); 为 0 -> 慢闪(表示已锁定)
 *   标定方法: 改 led_ctrl.c 里 LED_BLINK_TABLE 的 ppb 断点即可(必须升序)
 *
 *   计时基准默认取 BSP 的 COUNTS_PER_SECOND / CPU 主频, 若与实际不符会导致
 *   闪烁频率整体成比例偏差, 可在编译时用 -DLED_TIMER_HZ=<实际Hz> 覆盖。
 *--------------------------------------------------------------------------*/
#define LED_FREQ_MIN_HZ     0.5     /* |X[1]| 很小: 2 秒一个周期   */
#define LED_FREQ_MAX_HZ     8.0     /* |X[1]| 很大: 闪得很快       */
#define LED_X1_MIN_PPB      0.0     /* 表下限                      */
#define LED_X1_MAX_PPB      200.0   /* 表上限, 超过按最大值处理    */

/* 每 1 秒更新一次目标频率时, 允许的最大变化量(Hz), 防止视觉上频率乱跳 */
#define LED_FREQ_SLEW_HZ    2.0

/* 半周期下限(us): 频率上限 8Hz 对应 62500us, 留余量取 20000us */
#define LED_HALF_PERIOD_MIN_US  20000U

/*---------------------------------------------------------------------------
 * 五、对外接口
 *--------------------------------------------------------------------------*/
void  led_ctrl_init(void);          /* 初始化引脚: 先灭灯, 取计时基准   */
void  led_update(void);             /* 每秒调一次: 由 |X[1]| 算新频率   */
void  led_ctrl_tick(void);          /* 主循环高频调: 计时并翻转 LED     */

int   led_pin_ready(void);          /* 1 = LED 引脚配置成功 */
double led_get_abs_x1(void);        /* 当前 |X[1]| (ppb)                */
double led_get_freq_hz(void);       /* 当前闪烁频率 (Hz)                */
uint32_t led_get_half_period_us(void); /* 当前半周期 (us)               */

#endif /* LED_CTRL_H */
